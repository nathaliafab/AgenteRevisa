package com.example.checkstyle;

public class ProcessadorDados {

    public void processar() {
        int a = 10;
        int b = 20;
        int c = a + b;
        int d = c * 2;
        int e = d - 5;
        int f = e + b;
        int g = f * 3;
        int h = g / 2;
        int i = h + a;
        int j = i - c;
        int k = j * d;
        int l = k + g;
        int m = l - f;
        int n = m + h;
        int o = n * a;
        System.out.println("Saida: " + o);
    }
}
